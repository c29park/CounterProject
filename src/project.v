    input signed [10:0] v;
    begin
      abs11 = v[10] ? (~v + 1'b1) : v;
    end
  endfunction

  // tiny diamond point (~3px manhattan radius)
  function dot2;
    input [9:0] px, py;
    input [9:0] cx, cy;
    reg signed [10:0] dx, dy;
    reg [10:0] adx, ady;
    reg [10:0] man;
    begin
      dx  = $signed({1'b0, px}) - $signed({1'b0, cx});
      dy  = $signed({1'b0, py}) - $signed({1'b0, cy});
      adx = abs11(dx);
      ady = abs11(dy);
      man = adx + ady;
      dot2 = (man <= 11'd3);
    end
  endfunction

